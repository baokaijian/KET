def normalize_word(raw: str) -> str:
    word = re.sub(r"\s+", " ", raw).strip()
    word = word.replace("a/an", "a / an")
    word = word.replace("all right/alright", "all right / alright")
    word = word.replace("cafe/café", "cafe / café")
    word = word.replace("centimetre/centimeter", "centimetre / centimeter")
    word = word.replace("yog(h)urt", "yog(h)urt")
    word = re.sub(r"\s*/\s*", " / ", word)
    return word.strip(" -–")


def key_for(word: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", word.lower()).strip()


def id_for(word: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "_", word.lower()).strip("_")
    return cleaned or "word"


def extract_main_words(pdf_path: Path) -> list[str]:
    reader = PdfReader(str(pdf_path))
    words: list[str] = []
    seen: set[str] = set()

    for page_index in range(3, min(24, len(reader.pages))):
        text = reader.pages[page_index].extract_text() or ""
        text = text.replace("yog(h)urt", "yoghurt")
        for line in text.splitlines():
            line = line.strip()
            if (
                not line
                or line.startswith("•")
                or line.startswith("©")
                or line in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
                or "Vocabulary" in line
                or line == "Schools"
            ):
                continue
            for match in ENTRY_RE.finditer(line):
                word = normalize_word(match.group(1))
                if not word or len(word) > 55 or "£" in word:
                    continue
                if key_for(word) not in seen:
                    seen.add(key_for(word))
                    WORD_POS[key_for(word)] = match.group(0)[match.group(0).find("(") + 1 : match.group(0).rfind(")")]
                    words.append(word)
    return words


def clean_appendix_term(raw: str) -> str:
    term = raw.strip()
    term = re.sub(r"\([^)]*\)", "", term)
    term = re.sub(r"\s+", " ", term).strip(" /-")
    term = term.replace("television / TV", "television")
    term = term.replace("jewellery / jewelry", "jewellery")
    term = term.replace("metre / meter", "metre")
    term = term.replace("litre / liter", "litre")
    return normalize_word(term)


def extract_appendix_topic_map(pdf_path: Path) -> dict[str, str]:
    reader = PdfReader(str(pdf_path))
    topic_map: dict[str, str] = {}
    headings = set(APPENDIX_TOPIC_TO_SCENE)
    current_heading = None

    for page_index in range(24, min(32, len(reader.pages))):
        text = reader.pages[page_index].extract_text() or ""
        for raw_line in text.splitlines():
            line = re.sub(r"\s+", " ", raw_line).strip()
            if (
                not line
                or line.startswith("©")
                or line in {"Vocabulary List", "Appendix 2", "Topic Lists"}
                or line.startswith("Page ")
            ):
                continue

            matched_heading = next((heading for heading in headings if line == heading), None)
            if matched_heading:
                current_heading = matched_heading
                continue
            if not current_heading:
                continue

            scene_id = APPENDIX_TOPIC_TO_SCENE[current_heading]
            pieces = re.split(r"\s{2,}", raw_line.strip())
            if len(pieces) <= 1:
                pieces = re.split(r"\s{3,}| {2,}", raw_line.strip())
            for piece in pieces:
                term = clean_appendix_term(piece)
                if not term or len(term) <= 1:
                    continue
                if re.search(r"Page|Vocabulary|Key and", term):
                    continue
                topic_map.setdefault(key_for(term), scene_id)
                for variant in re.split(r"\s*/\s*", term):
                    if variant and len(variant) > 1:
                        topic_map.setdefault(key_for(variant), scene_id)
    return topic_map


def extract_existing_words() -> dict[str, dict]:
    existing: dict[str, dict] = {}
    for path in sorted(OUT_DIR.glob("level-*.js")):
        text = path.read_text(encoding="utf-8")
        body = text[text.find("[") : text.rfind("]") + 1]
        body = re.sub(r",\s*\]", "]", body)
        try:
            items = json.loads(body)
        except json.JSONDecodeError:
            continue
        for item in items:
            existing[key_for(item.get("word", ""))] = item
    return existing


def pick_topic(word: str, appendix_map: dict[str, str], old: dict | None = None) -> dict:
    lowered = key_for(word)
    if lowered in appendix_map:
        return SCENE_BY_ID[appendix_map[lowered]]
    old_topic = (old or {}).get("topic")
    if old_topic in OLD_TOPIC_TO_SCENE:
        return SCENE_BY_ID[OLD_TOPIC_TO_SCENE[old_topic]]
    for scene in SCENES[:-2]:
        if lowered in {key_for(k) for k in scene["keywords"]}:
            return scene
    if any(token in lowered.split() for token in ["up", "down", "out", "off", "on", "in"]):
        return SCENE_BY_ID["exam_expressions"]
    return SCENE_BY_ID["full_review"]


def fallback_translation(word: str, scene: dict) -> str:
    return BASIC_TRANSLATIONS.get(word) or BASIC_TRANSLATIONS.get(key_for(word)) or f"{scene['scene']}词：{word}"


def choose_icon(word: str, scene: dict, old: dict) -> str:
    lowered = key_for(word)
    if lowered in WORD_ICON_OVERRIDES:
        return WORD_ICON_OVERRIDES[lowered]
    if word in WORD_ICON_OVERRIDES:
        return WORD_ICON_OVERRIDES[word]
    if lowered in MONTHS or lowered in DAYS or any(token in lowered.split() for token in {"today", "tomorrow", "yesterday", "week", "year", "hour", "minute"}):
        return "Calendar"
    if lowered in NUMBER_WORDS or re.fullmatch(r"\d+", lowered):
        return "Hash"
    if lowered in POSITION_WORDS:
        return "Compass"
    tokens = set(lowered.split())
    for hints, icon in ICON_TOKEN_HINTS:
        if tokens & hints:
            return icon
    old_icon = old.get("icon")
    if old_icon and old_icon != scene["icon"]:
        return old_icon
    pos = WORD_POS.get(lowered, "")
    if "phr v" in pos:
        return "Zap"
    if "prep" in pos:
        return "Compass"
    if "v" in pos:
        return "Activity"
    if "adj" in pos:
        return "Smile"
    if "adv" in pos:
        return "Timer"
    if "pron" in pos:
        return "User"
    if "det" in pos:
        return "Tag"
    if "conj" in pos:
        return "MessageCircle"
    if "n" in pos:
        return "Package"
    return scene["icon"]


