def fallback_phonetic(word: str) -> str:
    if word in IPA_OVERRIDES:
        return IPA_OVERRIDES[word]
    parts = re.split(r"(\s+|/|-)", word)
    ipa_parts = []
    for part in parts:
        if part.isspace():
            ipa_parts.append(" ")
        elif part in {"/", "-"}:
            ipa_parts.append(" ")
        else:
            ipa_parts.append(ipa_for_word_piece(part))
    ipa = re.sub(r"\s+", " ", "".join(ipa_parts)).strip()
    return f"/{ipa}/" if ipa else "/-/"


def fallback_sentence(word: str, scene: dict) -> tuple[str, str]:
    safe_word = word.replace(" / ", " or ")
    english_scene = scene["name"].split(" ", 1)[-1]
    sentence = f'I can use "{safe_word}" in a {english_scene} scene.'
    translation = f'在“{scene["scene"]}”场景中练习使用 {word}。'
    return sentence, translation


def keep_existing_sentence(sentence: str | None) -> bool:
    if not sentence:
        return False
    return not (sentence.startswith('Use "') or sentence.startswith('I can use "'))


def spelling_enabled(word: str, level: int) -> bool:
    return level <= 6 and bool(re.fullmatch(r"[A-Za-z]{1,10}", word))


def build_words(main_words: list[str], existing: dict[str, dict], appendix_map: dict[str, str]) -> list[dict]:
    built = []
    counters = defaultdict(int)

    for word in main_words:
        old = existing.get(key_for(word), {})
        scene = pick_topic(word, appendix_map, old)
        counters[scene["level"]] += 1
        sentence, sentence_translation = fallback_sentence(word, scene)
        item = {
            "id": f"l{scene['level']}_{id_for(word)}",
            "word": word,
            "phonetic": old.get("phonetic") or fallback_phonetic(word),
            "translation": old.get("translation") or fallback_translation(word, scene),
            "level": scene["level"],
            "topic": scene["id"],
            "icon": choose_icon(word, scene, old),
            "sentence": old.get("sentence") if keep_existing_sentence(old.get("sentence")) else sentence,
            "sentenceTranslation": (
                old.get("sentenceTranslation")
                if keep_existing_sentence(old.get("sentence"))
                else sentence_translation
            ),
            "scene": scene["scene"],
            "scenePrompt": scene["prompt"],
            "difficulty": "basic" if scene["level"] <= 4 else "core" if scene["level"] <= 8 else "advanced",
            "spellingEnabled": bool(old.get("spellingEnabled", spelling_enabled(word, scene["level"]))),
            "source": "Cambridge A2 Key Vocabulary List 2025",
        }
        built.append(item)
    return built


