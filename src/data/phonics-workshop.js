export function blendCvcWord(onset, vowel, coda) {
  const combined = `${onset}${vowel}${coda}`.toLowerCase();
  const real = CVC_WORDS_DICTIONARY[combined];
  if (real) {
    return {
      word: combined,
      onset,
      vowel,
      coda,
      isRealWord: true,
      ipa: real.ipa,
      cn: real.cn,
      sentence: real.sentence,
      tip: `首音 ${onset} + 短元音 ${vowel} + 尾音 ${coda} → 真词 ${combined}（${real.cn}）`,
    };
  }
  return {
    word: combined,
    onset,
    vowel,
    coda,
    isRealWord: false,
    ipa: `/${onset}${vowel}${coda}/`,
    cn: "自然拼读解码练习词（伪词训练）",
    sentence: `Try blending the sounds: ${onset} - ${vowel} - ${coda}!`,
    tip: `虽然 ${combined} 不是日常词，但能拼读出来说明你掌握了 ${vowel} 的短元音解码规律！换个字母试试变成真词吧。`,
  };
}

